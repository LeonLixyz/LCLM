def read_bound(path, expected=None):
    payload = Path(path).read_bytes()
    if expected and hashlib.sha256(payload).hexdigest() != expected:
        raise ValueError(f"Manifest changed: {path}")
    return json.loads(payload)


def manifests():
    return {length: read_bound(FINAL / f"packed-cs16-{length}/manifest.json", sha)
            for length, sha in MANIFEST_SHAS.items()}


