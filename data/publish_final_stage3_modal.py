def stage_release(kind):
    """Construct an exact allowlist; never upload intermediate data or HF state."""
    docs = manifests()
    doc = docs[32768]
    if docs[16384]["raw_input_content_sha256_manifest"] != doc["raw_input_content_sha256_manifest"]:
        raise ValueError("16k/32k raw input certificates differ")
    stage = PUBLICATION / kind / "files"
    stage.mkdir(parents=True, exist_ok=True)
    entries = {}

    def add(source, relative, sha=None, rows=None, size=None):
        source, relative = Path(source), Path(relative)
        if relative.is_absolute() or ".." in relative.parts or relative.name == "state.json":
            raise ValueError(f"Unsafe upload path: {relative}")
        target = stage / relative
        if relative.as_posix() in entries:
            raise ValueError(f"Duplicate upload path: {relative}")
        actual_size = source.stat().st_size
        if size is not None and actual_size != size:
            raise ValueError(f"Changed source size: {source}")
        if sha is None:
            sha = hashlib.sha256(source.read_bytes()).hexdigest()
        target.parent.mkdir(parents=True, exist_ok=True)
        if target.is_symlink():
            if target.resolve() != source.resolve():
                raise ValueError(f"Staging link changed: {target}")
        elif target.exists():
            raise ValueError(f"Unexpected staged file: {target}")
        else:
            target.symlink_to(source)
        entries[relative.as_posix()] = {"bytes": actual_size, "sha256": sha,
                                       "source": str(source)}
        if rows is not None:
            entries[relative.as_posix()]["rows"] = rows

    for length, m in docs.items():
        manifest_name = f"packed-cs16-{length}/manifest.json" if kind == "packed" else f"provenance/packed-cs16-{length}-manifest.json"
        add(FINAL/f"packed-cs16-{length}/manifest.json", manifest_name, MANIFEST_SHAS[length])
        if kind == "packed":
            for record in m["output_files"]:
                add(FINAL/f"packed-cs16-{length}"/record["relative_path"],
                    f"packed-cs16-{length}/{record['relative_path']}", record["sha256"],
                    record["rows"], record["bytes"])
    if kind == "raw":
        names = {"base": "base", "native": "native_agents", "expansion": "expanded_agents"}
        roots = raw_roots(doc)
        for record in doc["raw_input_content_sha256_manifest"]:
            add(roots[record["kind"]]/record["name"],
                f"raw/{names[record['kind']]}/{record['name']}", record["content_sha256"],
                record["rows"], record.get("bytes"))
    for name, sha in EVIDENCE_SHAS.items():
        value = read_bound(FINAL/name, sha)
        if not all(v["status"] == "complete" for v in value.values()):
            raise ValueError(f"Incomplete evidence: {name}")
        add(FINAL/name, f"validation/{name}", sha)
    for name in ("base-source-provenance-inspection.json", "agent-source-manifest.json",
                 "nemotron-math-task-semantics-20260909.json"):
        add(ROOT/name, f"provenance/{name}")
    add(ROOT/"agents-transport/report.json", "provenance/native-agent-report.json")
    add(ROOT/"grouped-packing-20260909-v3/source-manifest.json", "provenance/base-native-source-manifest.json")
    expansion = doc["expansion_reviewed_transport_manifest"]
    selected = read_bound(expansion["selection_path"], expansion["selection_sha256"])
    if expansion["status"] != "reviewed_complete" or expansion["rows"] != 152503:
        raise ValueError("Unexpected expansion selection")
    add(expansion["selection_path"], "provenance/expansion-selection.json", expansion["selection_sha256"])
    generated = PUBLICATION/kind/"generated"
    generated.mkdir(parents=True, exist_ok=True)
    exp_path = generated/"expansion-reviewed-transport-manifest.json"
    exp_path.write_text(json.dumps(expansion, indent=2)+"\n")
    add(exp_path, "provenance/expansion-reviewed-transport-manifest.json")
    notice_root = ROOT/"source-notices-v1"
    notices = read_bound(notice_root/"index.json")
    add(notice_root/"index.json", "source-notices/index.json")
    for record in notices["sources"]:
        for file in record["files"]:
            relative = Path(record["component"])/record["key"]/file["upstream_path"]
            path = notice_root/relative
            if hashlib.sha256(path.read_bytes()).hexdigest() != file["sha256"]:
                raise ValueError(f"Source notice changed: {relative}")
            add(path, f"source-notices/{relative}", file["sha256"], size=file["bytes"])
    readme = generated/"README.md"
    readme.write_text(card(kind))
    add(readme, "README.md")
    release = {"schema": "stage3-final-hf-publication-v1", "build": "20260910",
        "repository": REPOS[kind], "kind": kind, "visibility": "private",
        "packed_manifest_sha256": MANIFEST_SHAS, "raw_rows": 21722787,
        "files": entries, "state_json_excluded": True,
        "upload_authorization": "User requested both raw and packed under leonli66; private repositories selected."}
    release_path = generated/"release.json"
    release_path.write_text(json.dumps(release, indent=2, sort_keys=True)+"\n")
    add(release_path, "release.json")
    volume.commit()
    return stage, entries


def verify_remote(api, repo, revision, entries, stage):
    """Match every uploaded file to the frozen build's size and content hash."""
    from huggingface_hub.hf_api import RepoFile
    files = {f.path: f for f in api.list_repo_tree(repo, repo_type="dataset", revision=revision,
             recursive=True) if isinstance(f, RepoFile)}
    extra = set(files) - set(entries) - {".gitattributes", "UPLOAD_STATUS.json"}
    missing = set(entries) - set(files)
    if extra or missing:
        raise ValueError(f"Remote file selection mismatch: extra={sorted(extra)[:10]}, missing={sorted(missing)[:10]}")
    for name, entry in entries.items():
        remote = files[name]
        if remote.size != entry["bytes"]:
            raise ValueError(f"Remote size mismatch: {name}")
        if remote.lfs is not None:
            if remote.lfs.sha256 != entry["sha256"]:
                raise ValueError(f"Remote SHA256 mismatch: {name}")
        else:
            payload = (stage/name).read_bytes()
            if hashlib.sha256(payload).hexdigest() != entry["sha256"]:
                raise ValueError(f"Local metadata changed: {name}")
            oid = hashlib.sha1(f"blob {len(payload)}\0".encode()+payload).hexdigest()
            if remote.blob_id != oid:
                raise ValueError(f"Remote Git blob mismatch: {name}")
    return {"files_verified": len(entries), "bytes_verified": sum(r["bytes"] for r in entries.values()),
            "parquet_files": sum(n.endswith(".parquet") for n in entries),
            "all_sizes_and_content_hashes_match": True, "state_json_present": False}


def finalize(api, kind, entries, stage, started):
    repo = REPOS[kind]
    info = api.repo_info(repo, repo_type="dataset")
    if not info.private:
        raise ValueError("Repository visibility changed during upload")
    result = verify_remote(api, repo, info.sha, entries, stage)
    result.update(status="complete", repo_id=repo, kind=kind, verified_payload_revision=info.sha,
                  elapsed_seconds=round(time.time()-started, 1), private=True)
    commit = api.upload_file(repo_id=repo, repo_type="dataset", path_in_repo="UPLOAD_STATUS.json",
                    path_or_fileobj=json.dumps(result, indent=2).encode(),
                    commit_message="Confirm every final file size and content hash",
                    parent_commit=info.sha)
    result["revision"] = commit.oid
    (PUBLICATION/kind/"completion.json").write_text(json.dumps(result, indent=2)+"\n")
    volume.commit()
    print(json.dumps(result), flush=True)
    return result


def load_staged_release(kind):
    stage = PUBLICATION/kind/"files"
    release = read_bound(stage/"release.json")
    if release["repository"] != REPOS[kind] or release["packed_manifest_sha256"] != {str(k):v for k,v in MANIFEST_SHAS.items()}:
        raise ValueError("Unexpected staged release")
    entries = release["files"]
    payload = (stage/"release.json").read_bytes()
    entries["release.json"] = {"bytes": len(payload), "sha256": hashlib.sha256(payload).hexdigest(),
                               "source": str(stage/"release.json")}
    return stage, entries


def local_upload_queue(kind, stage, entries):
    """Keep thousands of uploader metadata/lock operations off the remote FS."""
    from concurrent.futures import ThreadPoolExecutor
    local = Path("/tmp")/f"stage3-hf-{kind}"
    local.mkdir(parents=True, exist_ok=True)
    for relative, entry in entries.items():
        target = local/relative
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.is_symlink():
            target.symlink_to(entry["source"])
    cache = stage/".cache/huggingface/upload"
    cached = list(cache.rglob("*.metadata")) if cache.exists() else []
    def restore(source):
        target = local/".cache/huggingface/upload"/source.relative_to(cache)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, target)
    with ThreadPoolExecutor(max_workers=16) as pool:
        list(pool.map(restore, cached))
    print(json.dumps({"event": "local_queue_ready", "kind": kind, "cached_files": len(cached)}), flush=True)
    return local


@app.function(image=image, cpu=2, memory=4096, timeout=3600,
              volumes={"/data": volume, "/runs": agent_volume},
              secrets=[modal.Secret.from_name("huggingface")])
def verify_uploaded(kind: str):
    """Resume only verification after an upload; incomplete files fail closed."""
    from huggingface_hub import HfApi
    if kind not in REPOS:
        raise ValueError(kind)
    stage, entries = load_staged_release(kind)
    return finalize(HfApi(), kind, entries, stage, time.time())


@app.function(image=image, cpu=16, memory=32768, timeout=86400,
              volumes={"/data": volume, "/runs": agent_volume},
              secrets=[modal.Secret.from_name("huggingface")])
def publish(kind: str):
    from huggingface_hub import HfApi, hf_hub_download
    from huggingface_hub.errors import RepositoryNotFoundError
    if kind not in REPOS:
        raise ValueError(kind)
    started = time.time()
    api = HfApi()
    if api.whoami()["name"] != "leonli66":
        raise ValueError("Unexpected HF account")
    manifests()
    stage, entries = (load_staged_release(kind) if (PUBLICATION/kind/"files/release.json").exists()
                      else stage_release(kind))
    repo = REPOS[kind]
    # A retry may only resume a repository bearing this exact immutable release.
    try:
        info = api.repo_info(repo, repo_type="dataset")
    except RepositoryNotFoundError:
        api.create_repo(repo, repo_type="dataset", private=True, exist_ok=False)
    else:
        if not info.private:
            raise ValueError("Existing destination is not private")
        remote_marker = Path(hf_hub_download(repo, "release.json", repo_type="dataset", revision=info.sha))
        if remote_marker.read_bytes() != (stage/"release.json").read_bytes():
            raise ValueError("Existing destination belongs to another release")
    api.upload_file(repo_id=repo, repo_type="dataset", path_in_repo="release.json",
                    path_or_fileobj=str(stage/"release.json"), commit_message="Bind final audited data release")
    api.upload_file(repo_id=repo, repo_type="dataset", path_in_repo="UPLOAD_STATUS.json",
                    path_or_fileobj=json.dumps({"status": "uploading", "kind": kind}).encode(),
                    commit_message="Mark upload in progress")
    print(json.dumps({"event": "upload_start", "kind": kind, "repo": repo,
                      "files": len(entries), "bytes": sum(r["bytes"] for r in entries.values())}), flush=True)
    # Keep native transfer code out of the Modal runtime's heartbeat process.
    # Standard LFS was substantially faster than Xet in the bounded shard probe.
    worker_args = PUBLICATION/kind/"upload-arguments.json"
    local = local_upload_queue(kind, stage, entries)
    worker_args.write_text(json.dumps(dict(repo_id=repo, repo_type="dataset", folder_path=str(local),
                            private=True, allow_patterns=list(entries), ignore_patterns=IGNORE,
                            num_workers=16, print_report=True, print_report_every=60)))
    subprocess.run([sys.executable, "-u", "-c",
        "import json,sys; from huggingface_hub import HfApi; "
        "HfApi().upload_large_folder(**json.load(open(sys.argv[1])))", str(worker_args)], check=True)
    # Save only HF's resumable metadata, never lock files or data copies.
    cache = local/".cache/huggingface/upload"
    def save_metadata(source):
        target = stage/".cache/huggingface/upload"/source.relative_to(cache)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, target)
    from concurrent.futures import ThreadPoolExecutor
    with ThreadPoolExecutor(max_workers=16) as pool:
        list(pool.map(save_metadata, cache.rglob("*.metadata")))
    volume.commit()
    return finalize(api, kind, entries, stage, started)


@app.function(image=image, cpu=4, memory=8192, timeout=3600,
              volumes={"/data": volume, "/runs": agent_volume}, secrets=[modal.Secret.from_name("huggingface")])
def preflight():
    import collections
    import pyarrow.parquet as pq
    from huggingface_hub import HfApi
    docs = manifests()
    m = docs[32768]
    expansion = m["expansion_reviewed_transport_manifest"]
    roots = {"base": Path("/data/stage3-final-mixture-cot50-v1"),
             "native": ROOT / "agents-transport",
             "expansion": volume_path(expansion["transport_root"])}
    summary = {"account": HfApi().whoami()["name"], "raw": {}, "packed": {}}
    grouped = collections.defaultdict(list)
    for record in m["raw_input_content_sha256_manifest"]:
        grouped[record["kind"]].append(record)
    for kind, records in grouped.items():
        root = roots[kind]
        for record in records:
            path = root / record["name"]
            if not path.is_file():
                raise FileNotFoundError(path)
            if "bytes" in record and path.stat().st_size != record["bytes"]:
                raise ValueError(f"File size changed: {path}")
        summary["raw"][kind] = {"root": str(root), "files": len(records),
            "rows": sum(r["rows"] for r in records),
            "bytes": sum((root/r["name"]).stat().st_size for r in records),
            "schema": str(pq.read_schema(root/records[0]["name"]))}
    for length, doc in docs.items():
        root = FINAL / f"packed-cs16-{length}"
        for record in doc["output_files"]:
            path = root / record["relative_path"]
            if path.stat().st_size != record["bytes"]:
                raise ValueError(f"File size changed: {path}")
        summary["packed"][length] = {"files": len(doc["output_files"]),
            "rows": doc["packed_sequences"], "bytes": sum(r["bytes"] for r in doc["output_files"])}
    notices = read_bound(ROOT / "source-notices-v1/index.json")
    summary["notices"] = [{k: r[k] for k in ("component", "key", "source_id", "revision")}
                          for r in notices["sources"]]
    summary["provenance_exists"] = {name: (ROOT/name).exists() for name in
        ("base-source-provenance-inspection.json", "agent-source-manifest.json",
         "nemotron-math-task-semantics-20260909.json")}
    PUBLICATION.mkdir(parents=True, exist_ok=True)
    (PUBLICATION / "preflight.json").write_text(json.dumps(summary, indent=2)+"\n")
    volume.commit()
    return summary


@app.local_entrypoint()
def main(action: str = "preflight"):
    if action == "preflight":
        print(json.dumps(preflight.remote(), indent=2))
    elif action in REPOS:
        print(json.dumps(publish.remote(action), indent=2))
    elif action.startswith("verify-") and action[7:] in REPOS:
        print(json.dumps(verify_uploaded.remote(action[7:]), indent=2))
    elif action == "both":
        calls = {kind: publish.spawn(kind) for kind in REPOS}
        print(json.dumps({kind: call.object_id for kind, call in calls.items()}), flush=True)
        for kind, call in calls.items():
            print(json.dumps({kind: call.get()}, indent=2), flush=True)
    else:
        raise ValueError(action)
